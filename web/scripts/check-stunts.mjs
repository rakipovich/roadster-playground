import assert from 'node:assert/strict';
import {Quaternion,Vector3} from 'three';
import {stuntScore} from '../src/stunt-score.js';
const score=stuntScore(),q=new Quaternion(),axis=new Vector3(1,0,0);
let result;
score.update(1/60,{grounded:true,position:{x:0,z:0,y:0},upY:1},q);
for(let i=1;i<=120;i++)result=score.update(1/60,{grounded:false,position:{x:0,z:0,y:3},upY:Math.cos(i*Math.PI/60)},q.setFromAxisAngle(axis,i*Math.PI/60));
assert.ok(result.pending>=300);assert.equal(result.total,0);
for(let i=0;i<60;i++)result=score.update(1/60,{grounded:true,position:{x:0,z:0,y:0},upY:1},q);
assert.ok(result.total>=300);const total=result.total;
for(let i=0;i<60;i++)result=score.update(1/60,{grounded:true,position:{x:0,z:0,y:0},upY:1},q);
assert.equal(result.total,total);score.reset();
for(let i=0;i<120;i++)result=score.update(1/60,{grounded:false,position:{x:0,z:0,y:3},upY:1},q.setFromAxisAngle(axis,Math.sin(i*.2)*.5));
assert.ok(result.pending<100);score.reset();result=score.update(1/60,{grounded:true,position:{x:0,z:0,y:0},upY:1},q);assert.equal(result.pending,0);assert.equal(result.total,total);
console.log('Stunts: full turn, landing-only award, no duplicate awards, oscillation and reset pass.');

score.reset();
for(let i=0;i<180;i++)result=score.update(1/60,{grounded:false,position:{x:0,y:4,z:0},upY:1},new Quaternion());
assert.equal(result.pending,0,'hover earns nothing');
const before=result.total;
for(let i=0;i<120;i++)result=score.update(1/60,{grounded:false,chassisContact:true,position:{x:0,y:1,z:0},upY:-1},new Quaternion());
assert.equal(result.total,before,'crash loses pending combo, not banked score');assert.equal(result.pending,0);
console.log('Hover: zero reward; rollover: banked score kept and trick cancelled.');
score.reset(true);score.update(1/60,{grounded:true,position:{x:0,y:0,z:0},upY:1},new Quaternion());
for(let i=1;i<=120;i++)result=score.update(1/60,{grounded:false,position:{x:i*.1,y:3,z:0},upY:1},q.setFromAxisAngle(axis,i*Math.PI/60));
const prior=result.total;
for(let i=0;i<60;i++)result=score.update(1/60,{grounded:true,position:{x:12,y:0,z:0},upY:1,lastImpact:20},q);
assert.equal(result.total,prior+300,'upright stable landing survives a hard impact');assert.equal(result.event,'landed');
console.log('Recovered wheel landing awards the trick.');

score.reset();
const upright={grounded:true,position:{x:0,y:0,z:0},upY:1,angularSpeed:0};
result=score.update(1/60,upright,new Quaternion());const baseline=result.total;
for(let i=1;i<=360;i++)result=score.update(1/60,{grounded:false,position:{x:0,y:5,z:0},upY:Math.cos(i*Math.PI/60),angularSpeed:Math.PI},q.setFromAxisAngle(axis,i*Math.PI/60));
assert.equal(result.pending,900);
for(let i=0;i<8;i++)result=score.update(1/60,{grounded:false,chassisContact:true,position:{x:0,y:.5,z:0},upY:.2,angularSpeed:3},q);
for(let i=0;i<60;i++)result=score.update(1/60,{...upright,chassisContact:i<3,lastImpact:19},q);
assert.equal(result.total,baseline+900,'three rolls + brief scrape + wheel landing must award 900, not penalize');
console.log('Regression: three rolls, brief scrape, stable wheel landing = +900.');
